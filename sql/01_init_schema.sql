-- 3.2. fin_billing.care_programs
-- -----------------------------------------------------------------------------
CREATE TABLE fin_billing.care_programs (
    care_program_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code                   VARCHAR(32)    NOT NULL UNIQUE,
    program_name                   VARCHAR(120)   NOT NULL,
    description                    TEXT,
    target_risk_tier               VARCHAR(20)    NOT NULL,
    intervention_cost              NUMERIC(12, 2) NOT NULL,
    currency                       CHAR(3)        NOT NULL DEFAULT 'EUR',
    duration_days                  SMALLINT       NOT NULL,
    monthly_capacity_slots         INTEGER        NOT NULL,
    staff_hours_per_patient        NUMERIC(5, 2)  NOT NULL,
    expected_readmission_reduction NUMERIC(5, 4)  NOT NULL,
    effectiveness_ci_low           NUMERIC(5, 4)  NOT NULL,
    effectiveness_ci_high          NUMERIC(5, 4)  NOT NULL,
    is_active                      BOOLEAN        NOT NULL DEFAULT TRUE,
    effective_start_date           DATE           NOT NULL,
    effective_end_date             DATE,
    created_at                     TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at                     TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_care_programs_risk_tier
        CHECK (target_risk_tier IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL', 'ALL')),
    CONSTRAINT chk_care_programs_cost
        CHECK (intervention_cost >= 0 AND duration_days > 0),
    CONSTRAINT chk_care_programs_capacity
        CHECK (monthly_capacity_slots > 0 AND staff_hours_per_patient > 0),
    CONSTRAINT chk_care_programs_currency
        CHECK (currency IN ('EUR', 'CHF')),
    CONSTRAINT chk_care_programs_reduction_ci
        CHECK (
            effectiveness_ci_low >= 0 AND
            expected_readmission_reduction >= effectiveness_ci_low AND
            effectiveness_ci_high >= expected_readmission_reduction AND
            effectiveness_ci_high <= 1
        ),
    CONSTRAINT chk_care_programs_effective_dates
        CHECK (effective_end_date IS NULL OR effective_end_date >= effective_start_date)
);

COMMENT ON TABLE fin_billing.care_programs IS 'Programas de transição de cuidados pós-alta com custo unitário, capacidade operacional mensal e intervalos de eficácia para simulação Monte Carlo.';

CREATE INDEX idx_care_programs_effective_dates
    ON fin_billing.care_programs (effective_start_date, effective_end_date);

CREATE INDEX idx_care_programs_active
    ON fin_billing.care_programs (is_active)
    WHERE is_active = TRUE;

CREATE TRIGGER trg_care_programs_updated_at
    BEFORE UPDATE ON fin_billing.care_programs
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

