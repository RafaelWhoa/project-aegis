    ON fin_billing.encounter_billing (billing_date);

CREATE INDEX idx_encounter_billing_paid_date
    ON fin_billing.encounter_billing (paid_date);

CREATE INDEX idx_encounter_billing_patient_billing_date
    ON fin_billing.encounter_billing (patient_id, billing_date DESC);

