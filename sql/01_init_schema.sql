-- -----------------------------------------------------------------------------
-- 4.1. analytics.model_predictions
-- -----------------------------------------------------------------------------
CREATE TABLE analytics.model_predictions (
    prediction_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id               BIGINT         NOT NULL,
    patient_id                 BIGINT         NOT NULL,
    model_version              VARCHAR(60)    NOT NULL,
    split_name                 VARCHAR(16)    NOT NULL DEFAULT 'test',
    y_true                     SMALLINT       NOT NULL,
    y_prob                     NUMERIC(7, 6)  NOT NULL,
    estimated_readmission_cost NUMERIC(12, 2) NOT NULL,
    predicted_at               TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_model_predictions_encounter_patient
        FOREIGN KEY (encounter_id, patient_id)
        REFERENCES ehr_clinical.encounters (encounter_id, patient_id)
        ON DELETE CASCADE,
    CONSTRAINT uq_model_predictions_enc_version
        UNIQUE (encounter_id, model_version),
    CONSTRAINT chk_model_predictions_split
        CHECK (split_name IN ('train', 'val', 'test', 'oot')),
    CONSTRAINT chk_model_predictions_y_true
        CHECK (y_true IN (0, 1)),
    CONSTRAINT chk_model_predictions_y_prob
        CHECK (y_prob >= 0.0 AND y_prob <= 1.0),
    CONSTRAINT chk_model_predictions_cost
        CHECK (estimated_readmission_cost >= 0)
);

