-- -----------------------------------------------------------------------------
-- 2.1. ehr_clinical.patients
-- -----------------------------------------------------------------------------
CREATE TABLE ehr_clinical.patients (
    patient_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mrn                       VARCHAR(32)   NOT NULL UNIQUE,
    first_name                VARCHAR(100)  NOT NULL,
    last_name                 VARCHAR(100)  NOT NULL,
    birth_date                DATE          NOT NULL,
    sex                       VARCHAR(16)   NOT NULL,
    postal_code               VARCHAR(15),
    payer_type                VARCHAR(20)   NOT NULL,
    -- Determinantes Sociais de Saúde (SDOH - contexto DACH)
    lives_alone               BOOLEAN       NOT NULL DEFAULT FALSE,
    nursing_care_level        SMALLINT      NOT NULL DEFAULT 0,
    distance_to_hospital_km   NUMERIC(6, 1) NOT NULL DEFAULT 5.0,
    has_primary_care_physician BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Controle administrativo (NÃO usar como feature na ABT para evitar leakage futuro)
    is_deceased               BOOLEAN       NOT NULL DEFAULT FALSE,
    deceased_date             DATE,
    created_at                TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at                TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_patients_sex
        CHECK (sex IN ('M', 'F', 'OTHER', 'UNKNOWN')),
    CONSTRAINT chk_patients_payer_type
        CHECK (payer_type IN ('GKV', 'PKV', 'BG', 'SELF_PAY')),
    CONSTRAINT chk_patients_pflegegrad
        CHECK (nursing_care_level BETWEEN 0 AND 5),
    CONSTRAINT chk_patients_distance
        CHECK (distance_to_hospital_km >= 0),
    CONSTRAINT chk_patients_deceased_date
        CHECK (deceased_date IS NULL OR deceased_date >= birth_date)
);

COMMENT ON TABLE ehr_clinical.patients IS 'Cadastro mestre de pacientes (MPI) com determinantes sociais (SDOH) e perfil de cobertura DACH (GKV/PKV/BG).';
COMMENT ON COLUMN ehr_clinical.patients.nursing_care_level IS 'Nível de dependência de cuidados de enfermagem (Pflegegrad 0 a 5 na Alemanha).';

CREATE INDEX idx_patients_birth_date
    ON ehr_clinical.patients (birth_date);

CREATE INDEX idx_patients_payer_type
    ON ehr_clinical.patients (payer_type);

CREATE INDEX idx_patients_deceased_date
    ON ehr_clinical.patients (deceased_date)
    WHERE deceased_date IS NOT NULL;

CREATE TRIGGER trg_patients_updated_at
    BEFORE UPDATE ON ehr_clinical.patients
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- -----------------------------------------------------------------------------
-- 2.2. ehr_clinical.encounters
-- -----------------------------------------------------------------------------
CREATE TABLE ehr_clinical.encounters (
    encounter_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id                BIGINT       NOT NULL,
    previous_encounter_id     BIGINT,
    encounter_number          VARCHAR(40)  NOT NULL UNIQUE,
    encounter_type            VARCHAR(20)  NOT NULL,
    admit_datetime            TIMESTAMPTZ  NOT NULL,
    discharge_datetime        TIMESTAMPTZ,
    admission_source          VARCHAR(30)  NOT NULL,
    discharge_disposition     VARCHAR(30),
    department                VARCHAR(60)  NOT NULL,
    primary_diagnosis_code    VARCHAR(16)  NOT NULL,
    primary_diagnosis_desc    VARCHAR(255),
    secondary_diagnosis_codes TEXT[]       NOT NULL DEFAULT '{}',
    -- Fotografia temporal do CCI no momento da admissão (evita leakage de comorbidades futuras)
    charlson_score_at_admit   SMALLINT     NOT NULL DEFAULT 0,
    attending_physician_id    VARCHAR(32),
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at                TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_encounters_patient
        FOREIGN KEY (patient_id)
        REFERENCES ehr_clinical.patients (patient_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_encounters_previous
        FOREIGN KEY (previous_encounter_id)
        REFERENCES ehr_clinical.encounters (encounter_id)
        ON DELETE SET NULL,
    CONSTRAINT uq_encounters_encounter_patient
        UNIQUE (encounter_id, patient_id),
    CONSTRAINT chk_encounters_type
        CHECK (encounter_type IN ('INPATIENT', 'EMERGENCY', 'OBSERVATION', 'OUTPATIENT', 'ICU')),
    CONSTRAINT chk_encounters_admission_source
        CHECK (admission_source IN ('EMERGENCY', 'ELECTIVE', 'URGENT', 'TRANSFER', 'REFERRAL', 'NEWBORN')),
    CONSTRAINT chk_encounters_discharge_disposition
        CHECK (
            discharge_disposition IS NULL OR
            discharge_disposition IN ('HOME', 'HOME_HEALTH', 'SNF', 'REHAB', 'TRANSFER', 'AMA', 'HOSPICE', 'EXPIRED')
        ),
    CONSTRAINT chk_encounters_cci_at_admit
        CHECK (charlson_score_at_admit >= 0),
    CONSTRAINT chk_encounters_dates
        CHECK (discharge_datetime IS NULL OR discharge_datetime >= admit_datetime),
    CONSTRAINT chk_encounters_prev_not_self
        CHECK (previous_encounter_id IS NULL OR previous_encounter_id <> encounter_id)
);

COMMENT ON TABLE ehr_clinical.encounters IS 'Internações hospitalares com snapshot temporal de comorbidades (charlson_score_at_admit) e suporte a análise longitudinal de readmissões.';

CREATE INDEX idx_encounters_patient_id
    ON ehr_clinical.encounters (patient_id);

CREATE INDEX idx_encounters_admit_datetime
    ON ehr_clinical.encounters (admit_datetime);

CREATE INDEX idx_encounters_discharge_datetime
    ON ehr_clinical.encounters (discharge_datetime);

CREATE INDEX idx_encounters_patient_admit
    ON ehr_clinical.encounters (patient_id, admit_datetime DESC);

CREATE INDEX idx_encounters_patient_discharge
    ON ehr_clinical.encounters (patient_id, discharge_datetime DESC);

CREATE INDEX idx_encounters_type_admit
    ON ehr_clinical.encounters (encounter_type, admit_datetime);

CREATE INDEX idx_encounters_previous_encounter_id
    ON ehr_clinical.encounters (previous_encounter_id)
    WHERE previous_encounter_id IS NOT NULL;

CREATE TRIGGER trg_encounters_updated_at
    BEFORE UPDATE ON ehr_clinical.encounters
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

