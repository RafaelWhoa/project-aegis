-- 2.3. ehr_clinical.vital_signs
-- -----------------------------------------------------------------------------
CREATE TABLE ehr_clinical.vital_signs (
    vital_sign_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id         BIGINT        NOT NULL,
    patient_id           BIGINT        NOT NULL,
    recorded_datetime    TIMESTAMPTZ   NOT NULL,
    heart_rate_bpm       SMALLINT      NOT NULL,
    systolic_bp_mmhg     SMALLINT      NOT NULL,
    diastolic_bp_mmhg    SMALLINT      NOT NULL,
    respiratory_rate_rpm SMALLINT      NOT NULL,
    spo2_pct             NUMERIC(4, 1) NOT NULL,
    temperature_c        NUMERIC(4, 1) NOT NULL,
    news2_score          SMALLINT      NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_vital_signs_patient
        FOREIGN KEY (patient_id)
        REFERENCES ehr_clinical.patients (patient_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_vital_signs_encounter_patient
        FOREIGN KEY (encounter_id, patient_id)
        REFERENCES ehr_clinical.encounters (encounter_id, patient_id)
        ON DELETE CASCADE,
    CONSTRAINT chk_vitals_ranges
        CHECK (
            heart_rate_bpm BETWEEN 25 AND 240 AND
            systolic_bp_mmhg BETWEEN 50 AND 260 AND
            diastolic_bp_mmhg BETWEEN 25 AND 160 AND
            respiratory_rate_rpm BETWEEN 6 AND 60 AND
            spo2_pct BETWEEN 50.0 AND 100.0 AND
            temperature_c BETWEEN 32.0 AND 43.0 AND
            news2_score BETWEEN 0 AND 20
        )
);

COMMENT ON TABLE ehr_clinical.vital_signs IS 'Sinais vitais registrados durante a internação (admissão e últimas 24h pré-alta) com escore de alerta precoce NEWS2.';

CREATE INDEX idx_vital_signs_patient_id
    ON ehr_clinical.vital_signs (patient_id);

CREATE INDEX idx_vital_signs_encounter_id
    ON ehr_clinical.vital_signs (encounter_id);

CREATE INDEX idx_vital_signs_recorded_datetime
    ON ehr_clinical.vital_signs (recorded_datetime);

CREATE INDEX idx_vital_signs_encounter_recorded
    ON ehr_clinical.vital_signs (encounter_id, recorded_datetime DESC);

CREATE INDEX idx_vital_signs_patient_recorded
    ON ehr_clinical.vital_signs (patient_id, recorded_datetime DESC);

