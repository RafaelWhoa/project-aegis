-- -----------------------------------------------------------------------------
-- 3.1. fin_billing.drg_costs
-- -----------------------------------------------------------------------------
CREATE TABLE fin_billing.drg_costs (
    drg_code                  VARCHAR(16)    PRIMARY KEY,
    drg_description           VARCHAR(255)   NOT NULL,
    mdc_code                  VARCHAR(16)    NOT NULL,
    drg_type                  VARCHAR(16)    NOT NULL,
    relative_weight           NUMERIC(8, 4)  NOT NULL,
    base_rate                 NUMERIC(10, 2) NOT NULL DEFAULT 4200.00,
    ugvd_days                 NUMERIC(5, 1)  NOT NULL DEFAULT 1.0,
    geometric_mean_los        NUMERIC(6, 2)  NOT NULL,
    ogvd_days                 NUMERIC(5, 1)  NOT NULL,
    consolidation_window_days SMALLINT       NOT NULL DEFAULT 30,
    standard_cost             NUMERIC(12, 2) NOT NULL,
    base_reimbursement        NUMERIC(12, 2) NOT NULL,
    currency                  CHAR(3)        NOT NULL DEFAULT 'EUR',
    effective_start_date      DATE           NOT NULL,
    effective_end_date        DATE,
    created_at                TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at                TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_drg_type
        CHECK (drg_type IN ('MEDICAL', 'SURGICAL')),
    CONSTRAINT chk_drg_relative_weight
        CHECK (relative_weight > 0 AND base_rate > 0),
    CONSTRAINT chk_drg_los_bounds
        CHECK (ugvd_days >= 0 AND geometric_mean_los >= ugvd_days AND ogvd_days >= geometric_mean_los),
    CONSTRAINT chk_drg_consolidation_window
        CHECK (consolidation_window_days >= 0),
    CONSTRAINT chk_drg_costs_non_negative
        CHECK (standard_cost >= 0 AND base_reimbursement >= 0),
    CONSTRAINT chk_drg_currency
        CHECK (currency IN ('EUR', 'CHF')),
    CONSTRAINT chk_drg_effective_dates
        CHECK (effective_end_date IS NULL OR effective_end_date >= effective_start_date)
);

COMMENT ON TABLE fin_billing.drg_costs IS 'Catálogo de custos e reembolsos G-DRG / SwissDRG com Basisfallwert (base_rate), limites uGVD/oGVD e janela de Fallzusammenführung.';

CREATE INDEX idx_drg_costs_effective_dates
    ON fin_billing.drg_costs (effective_start_date, effective_end_date);

CREATE INDEX idx_drg_costs_mdc_code
    ON fin_billing.drg_costs (mdc_code);

CREATE TRIGGER trg_drg_costs_updated_at
    BEFORE UPDATE ON fin_billing.drg_costs
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

