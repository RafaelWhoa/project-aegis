-- 3.3. fin_billing.encounter_billing
-- -----------------------------------------------------------------------------
CREATE TABLE fin_billing.encounter_billing (
    billing_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id               BIGINT         NOT NULL UNIQUE,
    patient_id                 BIGINT         NOT NULL,
    drg_code                   VARCHAR(16)    NOT NULL,
    care_program_id            BIGINT,
    payer_name                 VARCHAR(100)   NOT NULL,
    payer_type                 VARCHAR(20)    NOT NULL,
    claim_status               VARCHAR(20)    NOT NULL DEFAULT 'SUBMITTED',
    currency                   CHAR(3)        NOT NULL DEFAULT 'EUR',
    -- Custos e reembolso fechados pós-alta (NÃO usar como features de entrada do modelo!)
    total_charges              NUMERIC(12, 2) NOT NULL,
    total_cost                 NUMERIC(12, 2) NOT NULL,
    expected_reimbursement     NUMERIC(12, 2) NOT NULL,
    paid_amount                NUMERIC(12, 2) NOT NULL DEFAULT 0,
    is_case_consolidated       BOOLEAN        NOT NULL DEFAULT FALSE,
    drg_consolidation_loss     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    billing_date               DATE           NOT NULL,
    paid_date                  DATE,
    created_at                 TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at                 TIMESTAMPTZ    NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_encounter_billing_patient
        FOREIGN KEY (patient_id)
        REFERENCES ehr_clinical.patients (patient_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_encounter_billing_encounter_patient
        FOREIGN KEY (encounter_id, patient_id)
        REFERENCES ehr_clinical.encounters (encounter_id, patient_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_encounter_billing_drg
        FOREIGN KEY (drg_code)
        REFERENCES fin_billing.drg_costs (drg_code)
        ON DELETE RESTRICT,
    CONSTRAINT fk_encounter_billing_care_program
        FOREIGN KEY (care_program_id)
        REFERENCES fin_billing.care_programs (care_program_id)
        ON DELETE SET NULL,
    CONSTRAINT chk_encounter_billing_payer_type
        CHECK (payer_type IN ('GKV', 'PKV', 'BG', 'SELF_PAY')),
    CONSTRAINT chk_encounter_billing_status
        CHECK (claim_status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'PARTIAL', 'PAID', 'CONSOLIDATED', 'DENIED')),
    CONSTRAINT chk_encounter_billing_currency
        CHECK (currency IN ('EUR', 'CHF')),
    CONSTRAINT chk_encounter_billing_amounts
        CHECK (
            total_charges >= 0 AND
            total_cost >= 0 AND
            expected_reimbursement >= 0 AND
            paid_amount >= 0 AND
            drg_consolidation_loss >= 0
        ),
    CONSTRAINT chk_encounter_billing_dates
        CHECK (paid_date IS NULL OR paid_date >= billing_date)
);

COMMENT ON TABLE fin_billing.encounter_billing IS 'Faturamento DRG pós-alta por internação, incluindo perda por Fallzusammenführung (consolidação de caso em reinternação <= 30 dias).';

CREATE INDEX idx_encounter_billing_patient_id
    ON fin_billing.encounter_billing (patient_id);

CREATE INDEX idx_encounter_billing_drg_code
    ON fin_billing.encounter_billing (drg_code);

CREATE INDEX idx_encounter_billing_care_program_id
    ON fin_billing.encounter_billing (care_program_id)
